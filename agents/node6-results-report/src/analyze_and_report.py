#!/usr/bin/env python3
"""
Node 6 — Analyze Results & Report
Analyzes Playwright test results (traces, screenshots, error logs),
classifies failures (true bug vs flaky vs environment),
auto-creates GitHub Issues for true failures,
and pushes metrics to Datadog.

Input:  Test results from Node 4 + Regression scope from Node 5
Output: Analysis report, GitHub Issues, Datadog metrics, Slack summary
"""

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path


# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------
OUTPUT_BASE = "/Users/vshere/Documents/Projects/QAEndToEnd/output"
JIRA_URL = os.environ.get("JIRA_URL", "https://legiontech.atlassian.net")


# ---------------------------------------------------------------------------
# Failure Classifier
# ---------------------------------------------------------------------------

class FailureClassifier:
    """Classifies test failures into categories."""

    FLAKY_PATTERNS = [
        "timeout", "timed out", "waiting for selector",
        "navigation timeout", "net::ERR_", "ECONNREFUSED",
        "detached", "target closed", "context destroyed",
    ]

    ENV_PATTERNS = [
        "ECONNREFUSED", "ENOTFOUND", "503", "502", "500",
        "health check failed", "service unavailable",
        "connection refused", "dns resolution",
    ]

    def classify(self, failure: dict) -> str:
        """Returns: 'true_failure' | 'flaky' | 'env_issue'"""
        error = (failure.get("error") or "").lower()
        title = (failure.get("title") or "").lower()

        # Check environment issues first
        if any(p in error for p in self.ENV_PATTERNS):
            return "env_issue"

        # Check flaky patterns
        if any(p in error for p in self.FLAKY_PATTERNS):
            return "flaky"

        # Default: true failure
        return "true_failure"

    def get_severity(self, failure: dict, story_priority: str = "High") -> str:
        """Determine bug severity based on failure context."""
        error = (failure.get("error") or "").lower()

        if "assert" in error and ("crash" in error or "unhandled" in error):
            return "critical"
        if story_priority in ("Highest", "High"):
            return "major"
        return "minor"

    def get_component(self, failure: dict) -> str:
        """Determine component from failure context."""
        title = (failure.get("title") or "").lower()
        file_name = (failure.get("file") or "").lower()

        if "schedule" in title or "schedule" in file_name:
            return "SCH-Schedule"
        if "shift" in title or "shift" in file_name:
            return "SCH-Shifts"
        if "location" in title or "peer" in title or "p2p" in title:
            return "SCH-Locations"
        if "transition" in title:
            return "SCH-Transitions"
        if "employee" in title or "assignment" in title:
            return "SCH-Assignment"
        return "SCH-General"


# ---------------------------------------------------------------------------
# GitHub Issue Creator (template — actual creation needs GITHUB_TOKEN)
# ---------------------------------------------------------------------------

def create_github_issue_template(failure: dict, story_id: str, classification: str, severity: str, component: str) -> dict:
    """Create a GitHub Issue template for a true failure."""
    title = f"[QA-Auto] {story_id}: {failure.get('title', 'Test Failure')}"

    body = f"""## Bug Report — Auto-generated by QA Pipeline

**Story:** [{story_id}]({JIRA_URL}/browse/{story_id})
**Classification:** {classification}
**Severity:** {severity}
**Component:** {component}
**Feature File:** `{failure.get('file', 'unknown')}`

### Failure Details
**Scenario:** {failure.get('title', 'N/A')}
**Error:**
```
{failure.get('error', 'No error message captured')[:500]}
```

### Repro Steps
1. Run the test scenario: `{failure.get('title', '')}`
2. Environment: RC (cinemark-wkdy)
3. Browser: Chromium (headless)

### Artifacts
- Trace file: Available in test-results directory
- Screenshot: Available in test-results directory

### Labels
`bug`, `qa-auto`, `{severity}`, `{component}`, `{story_id}`

---
*Auto-created by QA Pipeline Node 6 — Analyze Results & Report*
"""

    return {
        "title": title,
        "body": body,
        "labels": ["bug", "qa-auto", severity, component.lower()],
        "assignees": [],
        "story_id": story_id,
        "severity": severity,
        "component": component,
        "classification": classification,
    }


# ---------------------------------------------------------------------------
# Metrics Calculator
# ---------------------------------------------------------------------------

def calculate_metrics(test_results: dict, classifications: list, story_id: str, team: str) -> dict:
    """Calculate QA metrics for Datadog / reporting."""
    tr = test_results.get("test_results", {})
    total = tr.get("total", 0)
    passed = tr.get("passed", 0)
    failed = tr.get("failed", 0)
    flaky = tr.get("flaky", 0)
    duration_ms = test_results.get("duration_ms", 0)

    true_failures = len([c for c in classifications if c["classification"] == "true_failure"])
    flaky_count = len([c for c in classifications if c["classification"] == "flaky"])
    env_issues = len([c for c in classifications if c["classification"] == "env_issue"])

    pass_rate = round((passed / total * 100), 1) if total > 0 else 0
    flakiness_index = round((flaky_count / total * 100), 1) if total > 0 else 0

    return {
        "story_id": story_id,
        "team": team,
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "test_execution": {
            "total": total,
            "passed": passed,
            "failed": failed,
            "flaky": flaky,
            "pass_rate": pass_rate,
            "duration_ms": duration_ms,
        },
        "failure_analysis": {
            "true_failures": true_failures,
            "flaky": flaky_count,
            "env_issues": env_issues,
        },
        "quality_indicators": {
            "pass_rate": pass_rate,
            "flakiness_index": flakiness_index,
            "sla_compliance": duration_ms < 300000,  # 5 min SLA
            "regression_risk": "HIGH" if true_failures > 0 else ("MEDIUM" if flaky_count > 0 else "LOW"),
        },
        "datadog_metrics": [
            {"metric": f"qa.{team.lower()}.pass_rate", "value": pass_rate, "type": "gauge"},
            {"metric": f"qa.{team.lower()}.total_tests", "value": total, "type": "count"},
            {"metric": f"qa.{team.lower()}.failures", "value": failed, "type": "count"},
            {"metric": f"qa.{team.lower()}.flakiness", "value": flakiness_index, "type": "gauge"},
            {"metric": f"qa.{team.lower()}.duration_ms", "value": duration_ms, "type": "gauge"},
            {"metric": f"qa.{team.lower()}.true_failures", "value": true_failures, "type": "count"},
        ],
    }


# ---------------------------------------------------------------------------
# Report Generator
# ---------------------------------------------------------------------------

def generate_report(
    story_id: str,
    team: str,
    test_results: dict,
    regression_scope: dict,
    classifications: list,
    github_issues: list,
    metrics: dict,
) -> dict:
    """Generate the full analysis report."""

    tr = test_results.get("test_results", {})

    return {
        "story_id": story_id,
        "team": team,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "test_execution_summary": {
            "total": tr.get("total", 0),
            "passed": tr.get("passed", 0),
            "failed": tr.get("failed", 0),
            "flaky": tr.get("flaky", 0),
            "pass_rate": tr.get("pass_rate", 0),
            "duration_ms": test_results.get("duration_ms", 0),
        },
        "failure_analysis": {
            "total_failures": len(classifications),
            "true_failures": [c for c in classifications if c["classification"] == "true_failure"],
            "flaky_tests": [c for c in classifications if c["classification"] == "flaky"],
            "env_issues": [c for c in classifications if c["classification"] == "env_issue"],
        },
        "regression_scope": {
            "testrail_direct_impact": regression_scope.get("analysis_phases", {}).get("phase1_testrail", {}).get("direct_impact", {}),
            "testrail_indirect_impact": regression_scope.get("analysis_phases", {}).get("phase1_testrail", {}).get("indirect_impact", {}),
            "automation_code_scenarios": regression_scope.get("analysis_phases", {}).get("phase2_automation_code", {}).get("impacted_scenarios", 0),
            "dev_code_checklist_items": (
                regression_scope.get("analysis_phases", {}).get("phase3_dev_code", {}).get("backend", {}).get("test_checklist_items", 0) +
                regression_scope.get("analysis_phases", {}).get("phase3_dev_code", {}).get("frontend", {}).get("test_checklist_items", 0)
            ),
        },
        "github_issues": github_issues,
        "metrics": metrics,
        "recommendation": regression_scope.get("recommendation", {}),
    }


def generate_markdown_report(report: dict) -> str:
    """Generate human-readable markdown report."""
    story_id = report["story_id"]
    team = report["team"]
    ts = report["test_execution_summary"]
    fa = report["failure_analysis"]
    rs = report["regression_scope"]

    lines = []
    lines.append(f"# QA Pipeline Report — {story_id}")
    lines.append(f"")
    lines.append(f"**Team:** {team} | **Generated:** {report['generated_at'][:19]}Z")
    lines.append(f"")
    lines.append(f"---")
    lines.append(f"")
    lines.append(f"## Test Execution Summary")
    lines.append(f"")
    lines.append(f"| Metric | Value |")
    lines.append(f"|--------|-------|")
    lines.append(f"| Total Tests | {ts['total']} |")
    lines.append(f"| Passed | {ts['passed']} |")
    lines.append(f"| Failed | {ts['failed']} |")
    lines.append(f"| Flaky | {ts['flaky']} |")
    lines.append(f"| Pass Rate | {ts['pass_rate']}% |")
    lines.append(f"| Duration | {ts['duration_ms']}ms |")
    lines.append(f"")

    lines.append(f"## Failure Analysis")
    lines.append(f"")
    lines.append(f"| Category | Count |")
    lines.append(f"|----------|-------|")
    lines.append(f"| True Failures | {len(fa['true_failures'])} |")
    lines.append(f"| Flaky Tests | {len(fa['flaky_tests'])} |")
    lines.append(f"| Environment Issues | {len(fa['env_issues'])} |")
    lines.append(f"")

    if fa["true_failures"]:
        lines.append(f"### True Failures")
        lines.append(f"")
        for f in fa["true_failures"]:
            lines.append(f"- **{f['title']}** ({f['severity']}, {f['component']})")
            lines.append(f"  - Error: `{f.get('error', 'N/A')[:100]}`")
        lines.append(f"")

    if fa["flaky_tests"]:
        lines.append(f"### Flaky Tests")
        lines.append(f"")
        for f in fa["flaky_tests"]:
            lines.append(f"- **{f['title']}** — {f.get('error', 'N/A')[:80]}")
        lines.append(f"")

    lines.append(f"## Regression Impact Scope")
    lines.append(f"")
    lines.append(f"| Phase | Scope |")
    lines.append(f"|-------|-------|")
    di = rs.get("testrail_direct_impact", {})
    ii = rs.get("testrail_indirect_impact", {})
    lines.append(f"| TestRail Direct Impact | {di.get('total', 0)} cases ({di.get('automated', 0)} auto, {di.get('manual', 0)} manual) |")
    lines.append(f"| TestRail Indirect Impact | {ii.get('total', 0)} cases ({ii.get('automated', 0)} auto, {ii.get('manual', 0)} manual) |")
    lines.append(f"| Automation Code Scenarios | {rs.get('automation_code_scenarios', 0)} |")
    lines.append(f"| Dev Code Checklist Items | {rs.get('dev_code_checklist_items', 0)} |")
    lines.append(f"")

    if report.get("github_issues"):
        lines.append(f"## GitHub Issues Created")
        lines.append(f"")
        for issue in report["github_issues"]:
            lines.append(f"- **{issue['title']}** [{issue['severity']}] ({issue['component']})")
        lines.append(f"")

    lines.append(f"## Quality Indicators")
    lines.append(f"")
    qi = report.get("metrics", {}).get("quality_indicators", {})
    lines.append(f"| Indicator | Value |")
    lines.append(f"|-----------|-------|")
    lines.append(f"| Pass Rate | {qi.get('pass_rate', 0)}% |")
    lines.append(f"| Flakiness Index | {qi.get('flakiness_index', 0)}% |")
    lines.append(f"| SLA Compliance | {'Yes' if qi.get('sla_compliance') else 'No'} |")
    lines.append(f"| Regression Risk | {qi.get('regression_risk', 'N/A')} |")
    lines.append(f"")
    lines.append(f"---")
    lines.append(f"*Generated by QA Pipeline Node 6 — Analyze Results & Report*")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Node 6 — Analyze Results & Report")
    parser.add_argument("--story-id", required=True, help="Story ID (e.g., ER-2600)")
    parser.add_argument("--team", default="SCH", help="Team name")
    parser.add_argument("--test-results", required=True, help="Path to test-execution-results.json from Node 4")
    parser.add_argument("--regression-scope", required=True, help="Path to impact-summary.json from Node 5")
    parser.add_argument("--output-dir", default="", help="Output directory (defaults to output/<team>/reports/<story-id>)")
    args = parser.parse_args()

    # Set output dir
    if not args.output_dir:
        args.output_dir = os.path.join(OUTPUT_BASE, args.team, "reports", args.story_id)
    os.makedirs(args.output_dir, exist_ok=True)

    print(f"{'='*50}")
    print(f"NODE 6 — Analyze Results & Report")
    print(f"{'='*50}")
    print(f"Story ID: {args.story_id}")
    print(f"Team: {args.team}")
    print()

    # Load inputs
    with open(args.test_results, "r") as f:
        test_results = json.load(f)
    with open(args.regression_scope, "r") as f:
        regression_scope = json.load(f)

    # Step 1: Classify failures
    print("Step 1: Classifying failures...")
    classifier = FailureClassifier()
    failures = test_results.get("test_results", {}).get("failures", [])
    classifications = []
    for failure in failures:
        classification = classifier.classify(failure)
        severity = classifier.get_severity(failure, "Highest")
        component = classifier.get_component(failure)
        classifications.append({
            "title": failure.get("title", ""),
            "file": failure.get("file", ""),
            "error": failure.get("error", ""),
            "classification": classification,
            "severity": severity,
            "component": component,
        })
        print(f"  [{classification.upper()}] {failure.get('title', '')[:60]} — {severity}, {component}")

    # Step 2: Create GitHub Issue templates for true failures
    print(f"\nStep 2: Creating GitHub Issue templates...")
    github_issues = []
    true_failures = [c for c in classifications if c["classification"] == "true_failure"]
    for tf in true_failures:
        issue = create_github_issue_template(tf, args.story_id, tf["classification"], tf["severity"], tf["component"])
        github_issues.append(issue)
        print(f"  Issue: {issue['title']}")

    # Step 3: Calculate metrics
    print(f"\nStep 3: Calculating metrics...")
    metrics = calculate_metrics(test_results, classifications, args.story_id, args.team)
    qi = metrics["quality_indicators"]
    print(f"  Pass Rate: {qi['pass_rate']}%")
    print(f"  Flakiness Index: {qi['flakiness_index']}%")
    print(f"  SLA Compliance: {qi['sla_compliance']}")
    print(f"  Regression Risk: {qi['regression_risk']}")

    # Step 4: Generate report
    print(f"\nStep 4: Generating report...")
    report = generate_report(
        story_id=args.story_id,
        team=args.team,
        test_results=test_results,
        regression_scope=regression_scope,
        classifications=classifications,
        github_issues=github_issues,
        metrics=metrics,
    )

    # Write outputs
    report_json_path = os.path.join(args.output_dir, f"{args.story_id}-analysis-report.json")
    with open(report_json_path, "w") as f:
        json.dump(report, f, indent=2)

    report_md_path = os.path.join(args.output_dir, f"{args.story_id}-qa-report.md")
    md_content = generate_markdown_report(report)
    with open(report_md_path, "w") as f:
        f.write(md_content)

    metrics_path = os.path.join(args.output_dir, f"{args.story_id}-metrics.json")
    with open(metrics_path, "w") as f:
        json.dump(metrics, f, indent=2)

    if github_issues:
        issues_path = os.path.join(args.output_dir, f"{args.story_id}-github-issues.json")
        with open(issues_path, "w") as f:
            json.dump(github_issues, f, indent=2)

    print(f"\nOutputs written to: {args.output_dir}")
    print(f"  {args.story_id}-qa-report.md")
    print(f"  {args.story_id}-analysis-report.json")
    print(f"  {args.story_id}-metrics.json")
    if github_issues:
        print(f"  {args.story_id}-github-issues.json ({len(github_issues)} issues)")

    print(f"\n{'='*50}")
    print(f"NODE 6 — COMPLETE")
    print(f"{'='*50}")


if __name__ == "__main__":
    main()
