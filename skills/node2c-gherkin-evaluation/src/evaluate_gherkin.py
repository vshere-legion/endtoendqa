#!/usr/bin/env python3
"""
Node 2C — Gherkin Scenarios Evaluation (Skill)
Validates Gherkin scenarios generated by Node 2 for correct format,
completeness, tag compliance, and data-driven coverage.

Rejects malformed scenarios and loops back to Node 2 with fix instructions.
Max iterations: 3

Input:  .feature files from Node 2
Output: Approved scenarios or rejection with fix instructions
"""

import argparse
import json
import os
import re
import sys
from pathlib import Path


# ---------------------------------------------------------------------------
# Framework Tag Taxonomy (from Playwright-Nishant framework)
# ---------------------------------------------------------------------------

VALID_PRIORITY_TAGS = {"@P1-Critical", "@P2-High", "@P3-Medium", "@P4-Low"}
VALID_SUITE_TAGS = {"@Regression", "@NewFeature"}
VALID_TEST_TYPE_TAGS = {"@Positive", "@Negative"}
VALID_AVAILABILITY_TAGS = {"@GA", "@LA"}
VALID_MODE_TAGS = {"@mode:serial"}
VALID_TYPE_TAGS = {"@ui", "@api"}
VALID_TEAM_TAGS = {
    "@Team-SCH", "@Team-TA", "@Team-Platform",
    "@Team-PLT-Core", "@Team-PLT-Int", "@Team-PLT-Ops",
    "@Team-LRB", "@Team-EV-Com", "@Team-EV-LIP",
    "@Team-EV-ELM", "@Team-GENAI",
}
VALID_GROUP_TAGS_PREFIX = "@group-"


# ---------------------------------------------------------------------------
# Evaluation Rules
# ---------------------------------------------------------------------------

def rule_gherkin_format(feature_text: str, filename: str) -> list:
    """Rule 1: Enforce Given/When/Then structure in every scenario."""
    issues = []
    # Split into scenarios
    scenario_blocks = re.split(r'\n\s*(?=@step|Scenario[: ]|Scenario Outline[: ])', feature_text)

    scenario_num = 0
    for block in scenario_blocks:
        if not re.search(r'Scenario(?:\s+Outline)?:', block):
            continue
        scenario_num += 1

        # Extract scenario name
        name_match = re.search(r'Scenario(?:\s+Outline)?:\s*(.+)', block)
        scenario_name = name_match.group(1).strip() if name_match else f"Scenario #{scenario_num}"

        # Check for Given
        if not re.search(r'^\s+Given\s+', block, re.MULTILINE):
            issues.append({
                "file": filename,
                "scenario": scenario_name,
                "rule": "gherkin-format",
                "severity": "CRITICAL",
                "message": f"Missing 'Given' step in scenario '{scenario_name}'",
                "fix_instruction": "Add a 'Given' step to set up preconditions."
            })

        # Check for When
        if not re.search(r'^\s+When\s+', block, re.MULTILINE):
            issues.append({
                "file": filename,
                "scenario": scenario_name,
                "rule": "gherkin-format",
                "severity": "CRITICAL",
                "message": f"Missing 'When' step in scenario '{scenario_name}'",
                "fix_instruction": "Add a 'When' step to define the action."
            })

        # Check for Then
        if not re.search(r'^\s+Then\s+', block, re.MULTILINE):
            issues.append({
                "file": filename,
                "scenario": scenario_name,
                "rule": "gherkin-format",
                "severity": "CRITICAL",
                "message": f"Missing 'Then' step in scenario '{scenario_name}'",
                "fix_instruction": "Add a 'Then' step to define expected outcome."
            })

        # Check for orphaned And/But (without preceding Given/When/Then)
        lines = block.strip().split("\n")
        prev_is_step = False
        for line in lines:
            stripped = line.strip()
            if re.match(r'^(Given|When|Then)\s+', stripped):
                prev_is_step = True
            elif re.match(r'^(And|But)\s+', stripped):
                if not prev_is_step:
                    issues.append({
                        "file": filename,
                        "scenario": scenario_name,
                        "rule": "gherkin-format",
                        "severity": "CRITICAL",
                        "message": f"Orphaned 'And/But' step without preceding Given/When/Then",
                        "fix_instruction": "Ensure And/But follows a Given, When, or Then step."
                    })
                prev_is_step = True
            elif stripped and not stripped.startswith(("@", "Scenario", "Feature", "#", "|", "Examples")):
                prev_is_step = False

    return issues


def rule_examples_table(feature_text: str, filename: str) -> list:
    """Rule 2: Scenario Outlines MUST have Examples table with data."""
    issues = []
    # Find all Scenario Outlines
    outline_blocks = re.finditer(
        r'Scenario Outline:\s*(.+?)(?=\n\s*(?:@step|Scenario[: ]|Scenario Outline[: ])|\Z)',
        feature_text, re.DOTALL
    )

    for match in outline_blocks:
        scenario_name = match.group(1).strip().split("\n")[0]
        block = match.group(0)

        # Check for Examples keyword
        if "Examples:" not in block:
            issues.append({
                "file": filename,
                "scenario": scenario_name,
                "rule": "examples-table",
                "severity": "CRITICAL",
                "message": f"Scenario Outline '{scenario_name}' missing Examples table",
                "fix_instruction": "Add Examples: section with header row and at least 2 data rows."
            })
            continue

        # Check for placeholder variables in steps matching Examples header
        placeholders = set(re.findall(r'<(\w+)>', block))
        examples_section = block[block.index("Examples:"):]
        header_match = re.search(r'\|(.+)\|', examples_section)
        if header_match:
            headers = set(h.strip() for h in header_match.group(1).split("|") if h.strip())
            missing = placeholders - headers
            if missing:
                issues.append({
                    "file": filename,
                    "scenario": scenario_name,
                    "rule": "examples-table",
                    "severity": "CRITICAL",
                    "message": f"Placeholders {missing} not found in Examples header",
                    "fix_instruction": f"Add columns for {missing} to the Examples table."
                })

            # Count data rows (rows after header)
            table_rows = re.findall(r'\|.+\|', examples_section)
            data_rows = len(table_rows) - 1  # Subtract header
            if data_rows < 2:
                issues.append({
                    "file": filename,
                    "scenario": scenario_name,
                    "rule": "examples-table",
                    "severity": "WARNING",
                    "message": f"Examples table has only {data_rows} data row(s). Minimum 2 recommended.",
                    "fix_instruction": "Add more data rows to improve coverage."
                })

            # Check for empty cells
            for row in table_rows:
                cells = [c.strip() for c in row.split("|") if c.strip() != ""]
                if any(c == "" for c in cells):
                    issues.append({
                        "file": filename,
                        "scenario": scenario_name,
                        "rule": "examples-table",
                        "severity": "WARNING",
                        "message": "Empty cell detected in Examples table",
                        "fix_instruction": "Fill in all cells in the Examples table."
                    })
                    break

    return issues


def rule_scenario_coverage(feature_text: str, filename: str) -> list:
    """Rule 3: Check scenario coverage — need positive and negative tests."""
    issues = []

    has_positive = bool(re.search(r'@Positive', feature_text))
    has_negative = bool(re.search(r'@Negative', feature_text))

    if not has_positive:
        issues.append({
            "file": filename,
            "scenario": "Feature-level",
            "rule": "scenario-coverage",
            "severity": "WARNING",
            "message": "No @Positive (happy path) scenarios found",
            "fix_instruction": "Add at least one @Positive scenario for the happy path."
        })

    if not has_negative:
        issues.append({
            "file": filename,
            "scenario": "Feature-level",
            "rule": "scenario-coverage",
            "severity": "WARNING",
            "message": "No @Negative scenarios found",
            "fix_instruction": "Add at least one @Negative scenario for error/boundary cases."
        })

    return issues


def rule_feature_tags(feature_text: str, filename: str) -> list:
    """Rule 4: Validate feature-level tags match framework convention."""
    issues = []
    lines = feature_text.strip().split("\n")

    # First non-empty line should be tags
    tag_line = ""
    for line in lines:
        stripped = line.strip()
        if stripped and not stripped.startswith("#"):
            tag_line = stripped
            break

    if not tag_line.startswith("@"):
        issues.append({
            "file": filename,
            "scenario": "Feature-level",
            "rule": "feature-tags",
            "severity": "CRITICAL",
            "message": "Feature file must start with tags on the first line",
            "fix_instruction": "Add feature-level tags: @Team @type @mode:serial @feature @priority @suite @availability @group"
        })
        return issues

    tags = set(tag_line.split())

    # Check required tag categories
    has_team = any(t in VALID_TEAM_TAGS for t in tags)
    has_priority = any(t in VALID_PRIORITY_TAGS for t in tags)
    has_suite = any(t in VALID_SUITE_TAGS for t in tags)
    has_type = any(t in VALID_TYPE_TAGS for t in tags)
    has_mode = any(t in VALID_MODE_TAGS for t in tags)
    has_availability = any(t in VALID_AVAILABILITY_TAGS for t in tags)
    has_group = any(t.startswith(VALID_GROUP_TAGS_PREFIX) for t in tags)

    if not has_team:
        issues.append({
            "file": filename, "scenario": "Feature-level",
            "rule": "feature-tags", "severity": "CRITICAL",
            "message": "Missing team tag (e.g., @Team-SCH, @Team-TA)",
            "fix_instruction": f"Add one of: {', '.join(sorted(VALID_TEAM_TAGS))}"
        })
    if not has_priority:
        issues.append({
            "file": filename, "scenario": "Feature-level",
            "rule": "feature-tags", "severity": "WARNING",
            "message": "Missing priority tag (e.g., @P2-High)",
            "fix_instruction": f"Add one of: {', '.join(sorted(VALID_PRIORITY_TAGS))}"
        })
    if not has_suite:
        issues.append({
            "file": filename, "scenario": "Feature-level",
            "rule": "feature-tags", "severity": "WARNING",
            "message": "Missing suite tag (e.g., @Regression)",
            "fix_instruction": f"Add one of: {', '.join(sorted(VALID_SUITE_TAGS))}"
        })
    if not has_type:
        issues.append({
            "file": filename, "scenario": "Feature-level",
            "rule": "feature-tags", "severity": "WARNING",
            "message": "Missing type tag (@ui or @api)",
            "fix_instruction": "Add @ui or @api"
        })
    if not has_mode:
        issues.append({
            "file": filename, "scenario": "Feature-level",
            "rule": "feature-tags", "severity": "WARNING",
            "message": "Missing @mode:serial tag",
            "fix_instruction": "Add @mode:serial for sequential scenario execution"
        })
    if not has_availability:
        issues.append({
            "file": filename, "scenario": "Feature-level",
            "rule": "feature-tags", "severity": "WARNING",
            "message": "Missing availability tag (@GA or @LA)",
            "fix_instruction": "Add @GA (Generally Available) or @LA (Limited Availability)"
        })
    if not has_group:
        issues.append({
            "file": filename, "scenario": "Feature-level",
            "rule": "feature-tags", "severity": "WARNING",
            "message": "Missing group tag (e.g., @group-P2PLGTest)",
            "fix_instruction": "Add execution group tag for sharded runs"
        })

    return issues


def rule_scenario_tags(feature_text: str, filename: str) -> list:
    """Rule 5: Validate scenario-level tags (@step1, @Positive/@Negative)."""
    issues = []
    scenario_blocks = re.finditer(
        r'(\s*@[^\n]+)\n\s*(Scenario(?:\s+Outline)?:\s*.+)',
        feature_text
    )

    step_numbers_seen = set()
    for match in scenario_blocks:
        tag_line = match.group(1).strip()
        scenario_line = match.group(2).strip()
        scenario_name = re.sub(r'^Scenario(?:\s+Outline)?:\s*', '', scenario_line)
        tags = tag_line.split()

        # Check for @step tag
        step_tag = [t for t in tags if re.match(r'^@step\d+$', t)]
        if not step_tag:
            issues.append({
                "file": filename,
                "scenario": scenario_name,
                "rule": "scenario-tags",
                "severity": "WARNING",
                "message": f"Missing @step<N> tag on scenario '{scenario_name}'",
                "fix_instruction": "Add @step1, @step2, etc. for scenario ordering"
            })
        else:
            # Check for duplicate step numbers
            for st in step_tag:
                if st in step_numbers_seen:
                    issues.append({
                        "file": filename,
                        "scenario": scenario_name,
                        "rule": "scenario-tags",
                        "severity": "WARNING",
                        "message": f"Duplicate step tag {st} detected",
                        "fix_instruction": "Use unique sequential step numbers"
                    })
                step_numbers_seen.add(st)

        # Check for @Positive or @Negative
        has_test_type = any(t in VALID_TEST_TYPE_TAGS for t in tags)
        if not has_test_type:
            issues.append({
                "file": filename,
                "scenario": scenario_name,
                "rule": "scenario-tags",
                "severity": "WARNING",
                "message": f"Missing @Positive or @Negative tag on scenario '{scenario_name}'",
                "fix_instruction": "Add @Positive for happy-path or @Negative for error scenarios"
            })

    return issues


def rule_duplicate_scenarios(feature_text: str, filename: str) -> list:
    """Rule 6: No duplicate scenario names."""
    issues = []
    scenario_names = re.findall(r'Scenario(?:\s+Outline)?:\s*(.+)', feature_text)
    seen = {}
    for name in scenario_names:
        name_clean = name.strip()
        if name_clean in seen:
            issues.append({
                "file": filename,
                "scenario": name_clean,
                "rule": "duplicate-scenario",
                "severity": "CRITICAL",
                "message": f"Duplicate scenario name: '{name_clean}'",
                "fix_instruction": "Rename one of the duplicate scenarios to be unique."
            })
        seen[name_clean] = True

    return issues


def rule_background_auth(feature_text: str, filename: str) -> list:
    """Rule 7: Background should use framework auth pattern."""
    issues = []
    if "Background:" in feature_text:
        bg_match = re.search(r'Background:(.+?)(?=\n\s*@|\n\s*Scenario|\Z)', feature_text, re.DOTALL)
        if bg_match:
            bg_content = bg_match.group(1)
            if not re.search(r'Given I am logged in as', bg_content):
                issues.append({
                    "file": filename,
                    "scenario": "Background",
                    "rule": "background-auth",
                    "severity": "WARNING",
                    "message": "Background should use 'Given I am logged in as \"<UserType>\"' pattern",
                    "fix_instruction": "Replace login step with: Given I am logged in as \"SchedulingManager\""
                })
    return issues


