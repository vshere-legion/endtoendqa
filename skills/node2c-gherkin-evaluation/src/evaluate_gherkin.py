# Evaluator
# ---------------------------------------------------------------------------

def evaluate_feature_file(filepath: str) -> dict:
    """Run all evaluation rules against a .feature file."""
    filename = os.path.basename(filepath)
    with open(filepath, "r") as f:
        content = f.read()

    all_issues = []
    all_issues.extend(rule_gherkin_format(content, filename))
    all_issues.extend(rule_examples_table(content, filename))
    all_issues.extend(rule_scenario_coverage(content, filename))
    all_issues.extend(rule_feature_tags(content, filename))
    all_issues.extend(rule_scenario_tags(content, filename))
    all_issues.extend(rule_duplicate_scenarios(content, filename))
    all_issues.extend(rule_background_auth(content, filename))

    critical = [i for i in all_issues if i["severity"] == "CRITICAL"]
    warnings = [i for i in all_issues if i["severity"] == "WARNING"]

    return {
        "file": filename,
        "path": filepath,
        "status": "REJECTED" if critical else "APPROVED",
        "critical_count": len(critical),
        "warning_count": len(warnings),
        "issues": all_issues,
    }


def evaluate_all(input_path: str) -> dict:
    """Evaluate all .feature files in a directory or a single file."""
    results = []

    if os.path.isfile(input_path) and input_path.endswith(".feature"):
        results.append(evaluate_feature_file(input_path))
    elif os.path.isdir(input_path):
        for fpath in sorted(Path(input_path).glob("*.feature")):
            results.append(evaluate_feature_file(str(fpath)))
    else:
        print(f"ERROR: No .feature files found at {input_path}")
        sys.exit(1)

    total_critical = sum(r["critical_count"] for r in results)
    total_warnings = sum(r["warning_count"] for r in results)
    approved_files = [r for r in results if r["status"] == "APPROVED"]
    rejected_files = [r for r in results if r["status"] == "REJECTED"]

    return {
        "status": "REJECTED" if rejected_files else "APPROVED",
        "files_reviewed": len(results),
        "approved_files": len(approved_files),
        "rejected_files": len(rejected_files),
        "total_critical": total_critical,
        "total_warnings": total_warnings,
        "file_results": results,
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Node 2C — Gherkin Scenarios Evaluation")
    parser.add_argument("--input", required=True, help="Path to .feature file or directory of .feature files")
    parser.add_argument("--output", default="/tmp/outputs/gherkin-evaluation.json", help="Output file path")
    parser.add_argument("--approved-output", default="/tmp/outputs/approved-scenarios", help="Directory for approved .feature files")
    parser.add_argument("--iteration", type=int, default=1, help="Current iteration (max 3)")
    parser.add_argument("--max-iterations", type=int, default=3, help="Max allowed iterations")
    args = parser.parse_args()

    print(f"{'='*50}")
    print(f"NODE 2C — Gherkin Evaluation [SKILL]")
    print(f"{'='*50}")
    print(f"Input: {args.input}")
    print(f"Iteration: {args.iteration}/{args.max_iterations}")
    print()

    # Run evaluation
    result = evaluate_all(args.input)
    result["iteration"] = args.iteration
    result["max_iterations"] = args.max_iterations

    # Print results
    print(f"--- Evaluation Results ---")
    for fr in result["file_results"]:
        icon = "PASS" if fr["status"] == "APPROVED" else "FAIL"
        print(f"  [{icon}] {fr['file']} — {fr['critical_count']} critical, {fr['warning_count']} warnings")
        for issue in fr["issues"]:
            sev = "BLOCK" if issue["severity"] == "CRITICAL" else "WARN "
            print(f"    [{sev}] {issue['rule']}: {issue['message']}")

    print()
    print(f"Files reviewed: {result['files_reviewed']}")
    print(f"Approved: {result['approved_files']} | Rejected: {result['rejected_files']}")
    print(f"Critical: {result['total_critical']} | Warnings: {result['total_warnings']}")
    print(f"Gate Status: {result['status']}")

    # Copy approved files
    if result["approved_files"] > 0:
        os.makedirs(args.approved_output, exist_ok=True)
        for fr in result["file_results"]:
            if fr["status"] == "APPROVED":
                src = fr["path"]
                dst = os.path.join(args.approved_output, fr["file"])
                with open(src, "r") as sf:
                    with open(dst, "w") as df:
                        df.write(sf.read())

    # Write output
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w") as f:
        json.dump(result, f, indent=2)

    print(f"\nOutput: {args.output}")
    print(f"{'='*50}")

    if result["status"] == "APPROVED":
        print(f"APPROVED — Proceeding to Node 3 (Playwright Script Generation)")
    elif args.iteration >= args.max_iterations:
        print(f"BLOCKED — Max iterations ({args.max_iterations}) reached.")
        print(f"Escalating to #qa-end-to-end-vikas for manual intervention.")
        sys.exit(1)
    else:
        print(f"REJECTED — Returning fix instructions to Node 2 (iteration {args.iteration + 1}/{args.max_iterations})")
        sys.exit(1)

    print(f"{'='*50}")


if __name__ == "__main__":
    main()
